#!/usr/bin/env python3
"""Generate the palette files and ghostty, herdr and vim colours from oldschool.toml."""

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ["bg", "panel", "surface", "fg", "dim", "comment", "ink", "line", "bright", "blue",
         "orange", "red", "yellow", "green", "cyan", "purple"]

scheme = tomllib.loads((Path(__file__).parent / "oldschool.toml").read_text())
name = scheme["name"]
header = f"# generated by colorscheme/build.py from colorscheme/{name}.toml, edit that\n"

for mode in ("dark", "light"):
    colours = scheme[mode]

    lines = [header, f"mode={mode}\n"]
    lines += [f"{role}={colours[role]}\n" for role in ROLES]
    lines += [f"{key}={value}\n" for key, value in scheme["settings"].items()]
    (ROOT / f"palette/.config/palette/{mode}.env").write_text("".join(lines))

    term = colours["terminal"]
    lines = [header,
             f"background = #{term['background']}\n",
             f"foreground = #{term['foreground']}\n",
             f"cursor-color = #{term['cursor']}\n",
             f"cursor-text = #{term['cursor_text']}\n",
             f"selection-background = #{term['selection_bg']}\n",
             f"selection-foreground = #{term['selection_fg']}\n"]
    lines += [f"palette = {i}=#{c}\n" for i, c in enumerate(term["ansi"])]
    (ROOT / f"ghostty-theme/.config/ghostty-theme/themes/{name}-{mode}").write_text("".join(lines))

# herdr and vim pick dark or light themselves, so these hold both modes

# herdr layers these over a base theme; auto_switch follows the terminal
HERDR = {
    "panel_bg": "panel", "sidebar_bg": "bg", "active_row_bg": "surface",
    "selection_bg": "surface", "surface0": "panel", "surface1": "surface",
    "surface_dim": "bg", "overlay0": "dim", "overlay1": "dim", "text": "fg",
    "subtext0": "dim", "accent": "fg", "mauve": "purple", "green": "green",
    "yellow": "yellow", "red": "red", "peach": "orange", "blue": "blue",
    "teal": "cyan",
}
lines = [header, "onboarding = false\n\n[theme]\nauto_switch = true\n",
         'dark_name = "one-dark"\nlight_name = "catppuccin-latte"\n']
for mode in ("dark", "light"):
    lines.append(f"\n[theme.custom.{mode}]\n")
    lines += [f'{key} = "#{scheme[mode][role]}"\n' for key, role in HERDR.items()]
(ROOT / "herdr/.config/herdr/config.toml").write_text("".join(lines))

# (group, fg, bg, attr) as palette roles; "" leaves it unset
VIM = [
    ("Normal", "fg", "", ""), ("NormalFloat", "fg", "panel", ""),
    ("FloatBorder", "line", "panel", ""), ("Comment", "comment", "", "italic"),
    ("Constant", "purple", "", ""), ("String", "green", "", ""),
    ("Character", "green", "", ""), ("Number", "orange", "", ""),
    ("Boolean", "orange", "", ""), ("Identifier", "fg", "", ""),
    ("Function", "bright", "", ""), ("Statement", "orange", "", "bold"),
    ("Keyword", "orange", "", "bold"), ("Operator", "dim", "", ""),
    ("PreProc", "orange", "", ""), ("Include", "orange", "", ""),
    ("Type", "cyan", "", ""), ("Special", "yellow", "", ""),
    ("Delimiter", "dim", "", ""), ("Todo", "panel", "orange", "bold"),
    ("Underlined", "blue", "", "underline"), ("Error", "red", "", "bold"),
    ("ErrorMsg", "red", "", "bold"), ("WarningMsg", "orange", "", ""),
    ("Title", "bright", "", "bold"), ("Directory", "blue", "", ""),
    ("LineNr", "line", "", ""), ("CursorLineNr", "bright", "", "bold"),
    ("CursorLine", "", "panel", ""), ("ColorColumn", "", "panel", ""),
    ("SignColumn", "dim", "", ""), ("Visual", "", "surface", ""),
    ("Search", "panel", "orange", ""), ("IncSearch", "panel", "bright", ""),
    ("CurSearch", "panel", "bright", ""), ("MatchParen", "orange", "surface", "bold"),
    ("Pmenu", "fg", "panel", ""), ("PmenuSel", "panel", "fg", "bold"),
    ("PmenuSbar", "", "panel", ""), ("PmenuThumb", "", "dim", ""),
    ("StatusLine", "fg", "panel", ""), ("StatusLineNC", "dim", "panel", ""),
    ("TabLine", "dim", "panel", ""), ("TabLineSel", "panel", "fg", "bold"),
    ("TabLineFill", "", "panel", ""), ("VertSplit", "line", "", ""),
    ("WinSeparator", "line", "", ""), ("NonText", "line", "", ""),
    ("Whitespace", "line", "", ""), ("Folded", "dim", "panel", ""),
    ("DiffAdd", "green", "panel", ""), ("DiffChange", "yellow", "panel", ""),
    ("DiffDelete", "red", "panel", ""), ("DiffText", "panel", "yellow", ""),
    ("SpellBad", "red", "", "undercurl"), ("SpellCap", "orange", "", "undercurl"),
    ("WildMenu", "panel", "fg", ""), ("Question", "blue", "", ""),
    ("ModeMsg", "fg", "", "bold"), ("MoreMsg", "blue", "", ""),
    ("DiagnosticError", "red", "", ""), ("DiagnosticWarn", "orange", "", ""),
    ("DiagnosticInfo", "blue", "", ""), ("DiagnosticHint", "cyan", "", ""),
]

vheader = header.replace("# ", '" ', 1)
pick = ("let s:file = expand((empty($XDG_STATE_HOME) ? '~/.local/state' : $XDG_STATE_HOME) . '/theme-mode')\n"
        "let s:mode = filereadable(s:file) && get(readfile(s:file, '', 1), 0, '') ==# 'light' ? 'light' : 'dark'\n")
def vimdict(mode):
    return ", ".join(f"'{r}': '#{scheme[mode][r]}'" for r in ROLES)

palettes = "".join(f"let s:{mode} = {{{vimdict(mode)}}}\n" for mode in ("dark", "light"))
palettes += "let s:c = s:mode ==# 'light' ? s:light : s:dark\n"

def hi(group, fg, bg, attr):
    parts = [f"hi {group}"]
    parts.append(f"guifg='.s:c.{fg}.'" if fg else "guifg=NONE")
    parts.append(f"guibg='.s:c.{bg}.'" if bg else "guibg=NONE")
    parts.append(f"gui={attr or 'NONE'} cterm={attr or 'NONE'}")
    return "exe '" + " ".join(parts) + "'\n"

# background before hi clear, or nvim's own defaults (@variable, ...) keep the
# old mode's colours when :Theme switches modes
lines = [vheader, pick, "let &background = s:mode\n",
         "hi clear\nif exists('syntax_on') | syntax reset | endif\n",
         f"let g:colors_name = '{name}'\n", palettes]
lines += [hi(*row) for row in VIM]
(ROOT / f"vim-theme/.config/vim-theme/colors/{name}.vim").write_text("".join(lines))

# airline modes: [guifg, guibg, ctermfg, ctermbg] for the three sections
# airline reads the mode the colorscheme already set: another system() call
# at VimEnter can let terminal query replies leak into the buffer
lines = [vheader, "let s:mode = &background\n", palettes,
         f"let g:airline#themes#{name}#palette = {{}}\n",
         "function! s:map(key, fg, bg)\n"
         "  return airline#themes#generate_color_map([s:c.panel, s:c[a:bg], 0, 0], "
         "[s:c.fg, s:c.surface, 7, 0], [s:c[a:fg], s:c.panel, 7, 0])\n"
         "endfunction\n"]
for key, accent in (("normal", "fg"), ("insert", "bright"), ("visual", "orange"),
                    ("replace", "red"), ("commandline", "fg")):
    lines.append(f"let g:airline#themes#{name}#palette.{key} = s:map('{key}', 'fg', '{accent}')\n")
lines.append(f"let g:airline#themes#{name}#palette.inactive = airline#themes#generate_color_map("
             "[s:c.dim, s:c.panel, 8, 0], [s:c.dim, s:c.panel, 8, 0], [s:c.dim, s:c.panel, 8, 0])\n")
(ROOT / f"vim-theme/.config/vim-theme/autoload/airline/themes/{name}.vim").write_text("".join(lines))

print(f"built {name}: palette, ghostty, herdr and vim colours for dark and light")
